const express = require('express');
const puppeteer = require('puppeteer');

const app = express();
app.use(express.json());

app.post('/extract-intent', async (req, res) => {
    const { url } = req.body;
    if (!url) return res.status(400).json({ error: 'URL is required' });

    let browser = null;
    try {
        // --no-sandbox is strictly required for cloud hosting environments
        browser = await puppeteer.launch({
            args: ['--no-sandbox', '--disable-setuid-sandbox'] 
        });
        const page = await browser.newPage();
        
        // Disguise as a real Chrome browser
        await page.setUserAgent('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36');
        
        // networkidle0 waits until all JavaScript has finished executing
        await page.goto(url, { waitUntil: 'networkidle0', timeout: 12000 });
        
        const content = await page.content();
        
        // Hunt for the raw UPI string regardless of how it is embedded
        const match = content.match(/(upi:\/\/pay\?[^"'\s<>]+)/i);
        
        if (match) {
            // Clean up encoded HTML entities
            const decoded = match[1].replace(/&amp;/g, '&');
            res.json({ success: true, intent: decoded });
        } else {
            res.status(404).json({ success: false, error: 'UPI string not generated by page JS.' });
        }
    } catch (error) {
        res.status(500).json({ success: false, error: error.message });
    } finally {
        if (browser) await browser.close();
    }
});

const PORT = process.env.PORT || 3000;
app.listen(PORT, () => console.log(`Scraper microservice running on port ${PORT}`));